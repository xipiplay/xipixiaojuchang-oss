/// 提示词资源加载器：优先读取 App 打包资源（Bundle / Resources/Prompts），内置保底常量，不再依赖外部样本目录。
enum PipelinePromptStore {
    static func load(_ file: String) -> String {
        let name = file.hasSuffix(".txt") ? String(file.dropLast(4)) : file
        let filename = name + ".txt"

        // 1. Bundle 资源（Contents/Resources/Prompts/）
        if let url = Bundle.main.url(forResource: name, withExtension: "txt", subdirectory: "Prompts"),
           let text = try? String(contentsOf: url, encoding: .utf8), !text.isEmpty {
            return text
        }
        if let resourceURL = Bundle.main.resourceURL {
            let direct = resourceURL.appendingPathComponent("Prompts/\(filename)")
            if let text = try? String(contentsOf: direct, encoding: .utf8), !text.isEmpty {
                return text
            }
        }

        // 2. 当前工作目录（开发/测试环境 Resources/Prompts/）
        let localDir = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
            .appendingPathComponent("Resources/Prompts/\(filename)")
        if let text = try? String(contentsOf: localDir, encoding: .utf8), !text.isEmpty {
            return text
        }

        // 3. 内置保底常量
        if let fallback = embeddedPrompts[filename] ?? embeddedPrompts[name] {
            return fallback
        }
        return ""
    }

